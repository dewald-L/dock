// Package build compiles a dock binary that includes the native plugins
// listed in the config, the way xcaddy builds Caddy: it generates a small
// main module that imports dock plus each plugin package for its init
// side effect, then runs the Go toolchain on it.
package build

import (
	"bufio"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"runtime/debug"
	"strings"

	"github.com/dewald-L/dock/internal/config"
)

// DockModule is dock's own module path.
const DockModule = "github.com/dewald-L/dock"

// Dock says which dock source to build against.
type Dock struct {
	Path    string // local checkout (wins)
	Version string // module version; empty means latest
}

// ResolveDock picks the dock source: the config's Source, else the local
// checkout or released version the running binary was built from.
func ResolveDock(cfg *config.Config) Dock {
	if cfg.Source != "" {
		return Dock{Path: cfg.Source}
	}
	bi, ok := debug.ReadBuildInfo()
	if !ok {
		return Dock{}
	}
	if bi.Main.Path == DockModule {
		// Plain dock binary. Built inside a checkout: use that checkout
		// (Go stamps local builds with a VCS pseudo-version that may be
		// unpushed or +dirty, so it can't be fetched). Otherwise it was
		// `go install`ed at a real version.
		if dir := checkoutOfExecutable(); dir != "" {
			return Dock{Path: dir}
		}
		if v := bi.Main.Version; v != "" && v != "(devel)" && !strings.HasSuffix(v, "+dirty") {
			return Dock{Version: v}
		}
		return Dock{}
	}
	// A dock built by Build: dock is a dependency.
	for _, d := range bi.Deps {
		if d.Path != DockModule {
			continue
		}
		if d.Replace != nil && filepath.IsAbs(d.Replace.Path) {
			return Dock{Path: d.Replace.Path}
		}
		return Dock{Version: d.Version}
	}
	return Dock{}
}

// checkoutOfExecutable returns the directory of the running binary when it
// is a dock checkout (go build -o dock . inside the repo).
func checkoutOfExecutable() string {
	exe, err := os.Executable()
	if err != nil {
		return ""
	}
	if r, err := filepath.EvalSymlinks(exe); err == nil {
		exe = r
	}
	dir := filepath.Dir(exe)
	if mod, _ := ModulePath(dir); mod == DockModule {
		return dir
	}
	return ""
}

// ModulePath reads the module path from dir/go.mod.
func ModulePath(dir string) (string, error) {
	f, err := os.Open(filepath.Join(dir, "go.mod"))
	if err != nil {
		return "", err
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		if rest, ok := strings.CutPrefix(strings.TrimSpace(sc.Text()), "module "); ok {
			return strings.Trim(strings.TrimSpace(rest), `"`), nil
		}
	}
	return "", fmt.Errorf("%s/go.mod has no module line", dir)
}

// Dir is the build workspace.
func Dir() string {
	d, err := os.UserCacheDir()
	if err != nil {
		d = os.TempDir()
	}
	return filepath.Join(d, "dock", "build")
}

// Build compiles dock with plugins into out. Progress goes to log.
func Build(dock Dock, plugins []config.NativePlugin, out string, log io.Writer) error {
	goBin, err := exec.LookPath("go")
	if err != nil {
		return errors.New("building dock needs the Go toolchain (go) on PATH")
	}
	dir := Dir()
	if err := os.RemoveAll(dir); err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}

	var imports strings.Builder
	for _, p := range plugins {
		fmt.Fprintf(&imports, "\t_ %q\n", p.Package)
	}
	main := "// Code generated by dock build. DO NOT EDIT.\npackage main\n\nimport (\n" +
		"\t\"github.com/dewald-L/dock/cli\"\n\n" + imports.String() + ")\n\nfunc main() { cli.Main() }\n"
	if err := os.WriteFile(filepath.Join(dir, "main.go"), []byte(main), 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module dockbuild\n\ngo 1.24\n"), 0o644); err != nil {
		return err
	}

	output := func(args ...string) ([]byte, error) {
		c := exec.Command(goBin, args...)
		c.Dir = dir
		c.Env = append(os.Environ(), "GOFLAGS=-mod=mod", "GOWORK=off")
		var stderr strings.Builder
		c.Stderr = &stderr
		b, err := c.Output()
		if err != nil {
			msg := strings.TrimSpace(stderr.String() + "\n" + string(b))
			return nil, fmt.Errorf("go %s: %v\n%s", strings.Join(args, " "), err, msg)
		}
		return b, nil
	}
	run := func(args ...string) error {
		_, err := output(args...)
		return err
	}
	// Go only applies the main module's replace directives, so the build
	// module copies dock's (GitHub mirrors of golang.org/x, for networks
	// where the Go proxy refuses those) and local plugins'. The first
	// module to replace a path wins; dock and local plugins are already
	// replaced by their checkouts.
	replaced := map[string]bool{DockModule: true}
	copyReplaces := func(gomod string) error {
		b, err := output("mod", "edit", "-json", gomod)
		if err != nil {
			return err
		}
		for _, arg := range replaceArgs(b, filepath.Dir(gomod), replaced) {
			if err := run("mod", "edit", arg); err != nil {
				return err
			}
		}
		return nil
	}
	local := func(mod, path string) error {
		abs, err := filepath.Abs(path)
		if err != nil {
			return err
		}
		return run("mod", "edit", "-require="+mod+"@v0.0.0", "-replace="+mod+"="+abs)
	}

	// dock itself
	if dock.Path != "" {
		fmt.Fprintf(log, "dock: %s (local)\n", dock.Path)
		if err := local(DockModule, dock.Path); err != nil {
			return err
		}
		if err := copyReplaces(filepath.Join(dock.Path, "go.mod")); err != nil {
			return err
		}
	} else {
		v := dock.Version
		if v == "" {
			v = "latest"
		}
		fmt.Fprintf(log, "dock: %s@%s\n", DockModule, v)
		// fetch dock's go.mod alone first: its replaces must be in place
		// before its dependencies are resolved
		b, err := output("mod", "download", "-json", DockModule+"@"+v)
		if err != nil {
			return err
		}
		var dl struct{ GoMod string }
		if err := json.Unmarshal(b, &dl); err != nil || dl.GoMod == "" {
			return fmt.Errorf("go mod download %s@%s: no go.mod (%v)", DockModule, v, err)
		}
		if err := copyReplaces(dl.GoMod); err != nil {
			return err
		}
		if err := run("get", DockModule+"@"+v); err != nil {
			return err
		}
	}

	// plugins
	for _, p := range plugins {
		if p.Path != "" {
			mod, err := ModulePath(p.Path)
			if err != nil {
				return fmt.Errorf("%s: %w", p.Package, err)
			}
			if p.Package != mod && !strings.HasPrefix(p.Package, mod+"/") {
				return fmt.Errorf("%s is not inside module %s (%s)", p.Package, mod, p.Path)
			}
			fmt.Fprintf(log, "plugin: %s (local %s)\n", p.Package, p.Path)
			if mod == DockModule {
				continue // part of dock, already provided
			}
			if err := local(mod, p.Path); err != nil {
				return err
			}
			replaced[mod] = true
			if err := copyReplaces(filepath.Join(p.Path, "go.mod")); err != nil {
				return err
			}
			continue
		}
		if strings.HasPrefix(p.Package, DockModule+"/") {
			fmt.Fprintf(log, "plugin: %s (part of dock)\n", p.Package)
			continue // already provided by the dock source above
		}
		v := p.Version
		if v == "" {
			v = "latest"
		}
		fmt.Fprintf(log, "plugin: %s@%s\n", p.Package, v)
		if err := run("get", p.Package+"@"+v); err != nil {
			return err
		}
	}

	fmt.Fprintln(log, "resolving modules…")
	if err := run("mod", "tidy"); err != nil {
		return err
	}
	fmt.Fprintln(log, "compiling…")
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return err
	}
	tmp := out + ".new"
	if err := run("build", "-o", tmp, "."); err != nil {
		return err
	}
	return os.Rename(tmp, out) // atomic, safe while the old binary runs
}

// replaceArgs turns the replace directives in a `go mod edit -json` dump
// into `go mod edit` arguments for the build module. Directory targets are
// made absolute against dir (the go.mod's directory). Paths already in
// replaced are skipped; the rest are added to it.
func replaceArgs(modJSON []byte, dir string, replaced map[string]bool) []string {
	type modVer struct{ Path, Version string }
	var mf struct {
		Replace []struct{ Old, New modVer }
	}
	if json.Unmarshal(modJSON, &mf) != nil {
		return nil
	}
	var args []string
	for _, r := range mf.Replace {
		if replaced[r.Old.Path] {
			continue
		}
		replaced[r.Old.Path] = true
		old := r.Old.Path
		if r.Old.Version != "" {
			old += "@" + r.Old.Version
		}
		target := r.New.Path
		if r.New.Version != "" {
			target += "@" + r.New.Version
		} else if !filepath.IsAbs(target) {
			target = filepath.Join(dir, target)
		}
		args = append(args, "-replace="+old+"="+target)
	}
	return args
}
